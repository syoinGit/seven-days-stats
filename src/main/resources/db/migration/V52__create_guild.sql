-- Guild data is isolated from source game records. No source FK: retention must not erase people.
CREATE TABLE T_GUILD_LOCK (id INTEGER PRIMARY KEY);
INSERT INTO T_GUILD_LOCK VALUES (1);
CREATE TABLE M_GUILD_CHARACTER (
  id BIGSERIAL PRIMARY KEY,
  born_on DATE NOT NULL UNIQUE,
  game_id VARCHAR(40) NOT NULL,
  name VARCHAR(40) NOT NULL,
  introduction VARCHAR(500) NOT NULL,
  origin VARCHAR(500) NOT NULL,
  personality VARCHAR(500) NOT NULL,
  appearance VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ALIVE',
  CONSTRAINT ck_guild_status CHECK (status IN ('ALIVE', 'INJURED', 'MISSING', 'DEAD'))
);
CREATE TABLE T_GUILD_SOURCE (
  character_id BIGINT PRIMARY KEY REFERENCES M_GUILD_CHARACTER(id),
  source_key VARCHAR(200) NOT NULL UNIQUE,
  facts VARCHAR(1000) NOT NULL
);
CREATE TABLE T_GUILD_JOB (
  target_date DATE PRIMARY KEY,
  status VARCHAR(20) NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  message VARCHAR(300) NOT NULL,
  model_id VARCHAR(300) NOT NULL,
  version VARCHAR(40) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE T_GUILD_DAY (visit_date DATE PRIMARY KEY);
CREATE TABLE T_GUILD_VISIT (
  visit_date DATE NOT NULL REFERENCES T_GUILD_DAY(visit_date),
  character_id BIGINT NOT NULL REFERENCES M_GUILD_CHARACTER(id),
  seat INTEGER NOT NULL CHECK (seat BETWEEN 0 AND 4),
  morning VARCHAR(120) NOT NULL,
  afternoon VARCHAR(120) NOT NULL,
  evening VARCHAR(120) NOT NULL,
  PRIMARY KEY (visit_date, character_id),
  UNIQUE (visit_date, seat)
);
