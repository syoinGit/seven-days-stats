INSERT INTO T_TIMELINE_POST_REACTION (timeline_post_id, account_id, reaction_type, created_at)
SELECT tp.timeline_post_id, r.account_id,
       CASE WHEN r.reaction_type = 'HEART' THEN 'NICE' ELSE r.reaction_type END, r.created_at
