CREATE TABLE T_TIMELINE_POST (
    timeline_post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    post_type VARCHAR(40) NOT NULL,
    actor_type VARCHAR(20) NOT NULL,
    actor_player_id BIGINT,
    actor_name TEXT NOT NULL,
    message TEXT NOT NULL,
    coordinate VARCHAR(80),
    source_type VARCHAR(40) NOT NULL,
    source_id BIGINT,
    source_hash VARCHAR(100) NOT NULL UNIQUE,
    priority INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_t_timeline_post_published
    ON T_TIMELINE_POST (published_at DESC, timeline_post_id DESC);
CREATE INDEX idx_t_timeline_post_actor_type_published
    ON T_TIMELINE_POST (actor_player_id, post_type, published_at DESC);

CREATE TABLE T_TIMELINE_POST_REACTION (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timeline_post_id BIGINT NOT NULL REFERENCES T_TIMELINE_POST(timeline_post_id),
    account_id BIGINT NOT NULL REFERENCES M_WEB_ACCOUNT(id),
    reaction_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_t_timeline_post_reaction_account UNIQUE (timeline_post_id, account_id)
);

CREATE INDEX idx_t_timeline_post_reaction_post
    ON T_TIMELINE_POST_REACTION (timeline_post_id);

